#!/usr/bin/env node
/**
 * Generate lib/spatial-fillings/silhouette-master.ts from the traced M bottom
 * panel in .claude/PRD-xray-pillow-ux/reference/silhouette-master.json
 * (X-ray pillow UX slice 01). The trace has ~1000 vertices at 0.1 mm; the
 * x-ray needs far fewer, so the ring is simplified with Douglas–Peucker at
 * TOLERANCE_MM before it is written out. Deterministic: same input, same file.
 *
 * Usage: node scripts/gen-silhouette-master.mjs
 */
import fs from "node:fs";
import path from "node:path";

const SRC = path.join(".claude", "PRD-xray-pillow-ux", "reference", "silhouette-master.json");
const OUT = path.join("lib", "spatial-fillings", "silhouette-master.ts");
const TOLERANCE_MM = 0.4;

const src = JSON.parse(fs.readFileSync(SRC, "utf8"));
let pts = src.points.map(([x, y]) => [Number(x), Number(y)]);
// drop a duplicated closing vertex so the ring is open for simplification
if (pts.length > 1) {
  const [a, b] = [pts[0], pts[pts.length - 1]];
  if (Math.abs(a[0] - b[0]) < 1e-6 && Math.abs(a[1] - b[1]) < 1e-6) pts = pts.slice(0, -1);
}

function segDist(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const l2 = dx * dx + dy * dy;
  const t = l2 === 0 ? 0 : Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l2));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

function simplify(points, tol) {
  if (points.length < 3) return points;
  let maxD = -1;
  let idx = 0;
  const first = points[0];
  const last = points[points.length - 1];
  for (let i = 1; i < points.length - 1; i++) {
    const d = segDist(points[i], first, last);
    if (d > maxD) {
      maxD = d;
      idx = i;
    }
  }
  if (maxD <= tol) return [first, last];
  const left = simplify(points.slice(0, idx + 1), tol);
  const right = simplify(points.slice(idx), tol);
  return left.slice(0, -1).concat(right);
}

// Simplify as two halves split at the farthest vertex from the first, so the
// closed ring keeps both ends honest (plain DP on an open polyline would pin
// the first vertex and let the seam wander).
let far = 0;
let farD = -1;
for (let i = 1; i < pts.length; i++) {
  const d = Math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]);
  if (d > farD) {
    farD = d;
    far = i;
  }
}
const half1 = simplify(pts.slice(0, far + 1), TOLERANCE_MM);
const half2 = simplify(pts.slice(far).concat([pts[0]]), TOLERANCE_MM);
const ring = half1.slice(0, -1).concat(half2.slice(0, -1));

const width = Math.max(...pts.map((p) => p[0]));
const length = Math.max(...pts.map((p) => p[1]));
const body = ring.map(([x, y]) => `  [${x.toFixed(2)}, ${y.toFixed(2)}],`).join("\n");

const out = `/**
 * GENERATED by scripts/gen-silhouette-master.mjs — do not edit by hand.
 * Source: .claude/PRD-xray-pillow-ux/reference/silhouette-master.json, the
 * finished M bottom panel traced from the 2018 case drawing (Ivan, 25-9-2026:
 * the M shape is the silhouette for every Size, no neck tab). Frame: mm,
 * x = 0 at the left end, y = 0 at the back (wave) edge extreme, the notched
 * front edge at max y. Douglas–Peucker at ${TOLERANCE_MM} mm: ${pts.length} → ${ring.length} vertices.
 */

export const SILHOUETTE_MASTER_WIDTH_MM = ${width.toFixed(1)};
export const SILHOUETTE_MASTER_LENGTH_MM = ${length.toFixed(1)};

/** Closed ring, counter-clockwise, first vertex not repeated. */
export const SILHOUETTE_MASTER: readonly (readonly [number, number])[] = [
${body}
];
`;
fs.writeFileSync(OUT, out);
console.log(`${OUT}: ${pts.length} -> ${ring.length} vertices, ${width.toFixed(1)} x ${length.toFixed(1)} mm`);
