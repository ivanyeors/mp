import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  normaliseRows,
  planRows,
  type ExistingCustomer,
  type ExistingLookup,
} from "@/lib/customer-migration/plan";
import { readPreviewChunk, runShopifyPreview } from "@/lib/customer-migration/preview";
import { parseShopifyCustomersCsv } from "@/lib/customer-migration/shopify-csv";
import { applyPayload, importRows, readApplyChunk } from "@/lib/customer-migration/apply";
import { AGREEMENT_EXPORT, AGREEMENT_SEED, AGREEMENT_SPLIT, exportCsv, type SeedCustomer } from "./fixtures";

/**
 * The preview and the SQL function must agree (slice 03). `planCustomerRow`
 * forecasts; `import_shopify_customers` decides. Both run the same fixture:
 *
 *  - here, the TS preview runs AGREEMENT_EXPORT against AGREEMENT_SEED, and
 *    its row-by-row outcomes are `expected` in cases.json, beside the exact
 *    rows the server would hand the SQL function, chunk by chunk;
 *  - supabase/tests/customer-import/assert-agreement.sql seeds the same
 *    Customers, sends those chunks to the SQL function, and requires the same
 *    outcomes (scripts/check-customer-import-sql.sh).
 *
 * After changing the fixture or the plan rules, regenerate cases.json with
 *   UPDATE_SQL_CASES=1 pnpm vitest run lib/customer-migration/__tests__/sql-agreement.test.ts
 * and run the SQL check.
 */

const CASES_PATH = join(process.cwd(), "supabase/tests/customer-import/cases.json");

/** The seed as the preview's database read would return it. */
function lookupFromSeed(seed: readonly SeedCustomer[]): ExistingLookup {
  const customersByEmail = new Map<string, ExistingCustomer>();
  const migratedShopifyIds = new Set<string>();
  for (const c of seed) {
    customersByEmail.set(c.email.toLowerCase(), {
      customer_id: c.id,
      has_account: c.has_account,
      has_first_name: c.first_name !== null,
      has_last_name: c.last_name !== null,
      has_phone: c.phone !== null,
      has_address: c.address !== null,
      migrated: c.migrated ? { shopify_customer_id: c.migrated } : null,
    });
    if (c.migrated) migratedShopifyIds.add(c.migrated);
  }
  return { customersByEmail, migratedShopifyIds };
}

async function buildCases() {
  const text = exportCsv(AGREEMENT_EXPORT);
  const { rows } = parseShopifyCustomersCsv(text);

  // What the browser sends, read back the way the server reads it.
  const payload = JSON.parse(JSON.stringify(applyPayload(rows))) as unknown[];
  const chunks = [payload.slice(0, AGREEMENT_SPLIT), payload.slice(AGREEMENT_SPLIT)].map((chunk, k) => {
    const read = readApplyChunk(chunk, k === 0 ? 0 : AGREEMENT_SPLIT);
    if (!read.ok) throw new Error(read.error);
    return importRows(read.rows);
  });

  // The preview, as the page runs it, against the seed.
  const lookup = lookupFromSeed(AGREEMENT_SEED);
  const run = await runShopifyPreview(text, async (chunk) => {
    const read = readPreviewChunk(JSON.parse(JSON.stringify(chunk)));
    if (!read.ok) return read;
    return { ok: true, results: planRows(normaliseRows(read.rows), lookup) };
  });
  if (run.kind !== "done") throw new Error(`the preview did not finish: ${run.kind}`);
  const expected = run.previews.map(({ i, outcome, reason }) => (reason ? { i, outcome, reason } : { i, outcome }));

  return {
    about:
      "Generated by lib/customer-migration/__tests__/sql-agreement.test.ts (UPDATE_SQL_CASES=1). " +
      "Synthetic: invented names, example.com emails. `expected` is the TS preview's answer; the SQL " +
      "assert files require import_shopify_customers to give the same.",
    seed: AGREEMENT_SEED,
    chunks,
    expected,
  };
}

describe("the preview and import_shopify_customers run the same fixture", () => {
  it("cases.json holds the TS fixture, the rows as the server sends them, and the preview's outcomes", async () => {
    const cases = await buildCases();
    if (process.env.UPDATE_SQL_CASES) writeFileSync(CASES_PATH, `${JSON.stringify(cases, null, 2)}\n`);
    expect(JSON.parse(readFileSync(CASES_PATH, "utf8"))).toEqual(cases);
  });

  it("covers every outcome and skip reason the two must agree on", async () => {
    const { expected } = await buildCases();
    expect(expected).toEqual([
      { i: 0, outcome: "create" },
      { i: 1, outcome: "merge" },
      { i: 2, outcome: "merge" },
      { i: 3, outcome: "merge" },
      { i: 4, outcome: "already_imported" },
      { i: 5, outcome: "already_imported" },
      { i: 6, outcome: "skip", reason: "email_already_migrated" },
      { i: 7, outcome: "already_imported" },
      { i: 8, outcome: "skip", reason: "no_email" },
      { i: 9, outcome: "skip", reason: "invalid_email" },
      { i: 10, outcome: "skip", reason: "duplicate_email_in_file" },
      { i: 11, outcome: "skip", reason: "duplicate_email_in_file" },
      { i: 12, outcome: "skip", reason: "duplicate_customer_id_in_file" },
      { i: 13, outcome: "skip", reason: "duplicate_customer_id_in_file" },
      { i: 14, outcome: "create" },
      { i: 15, outcome: "create" },
      { i: 16, outcome: "create" },
      { i: 17, outcome: "create" },
    ]);
  });

  it("the duplicate split across the two chunks reaches the SQL function as a skip only the browser could see", async () => {
    const { chunks } = await buildCases();
    expect(chunks[0][10]).toEqual({ i: 10, skip: "duplicate_email_in_file" });
    expect(chunks[1][0]).toEqual({ i: 11, skip: "duplicate_email_in_file" });
  });

  it("sends Tags and Note to the SQL function, and Shopify ids as text", async () => {
    const { chunks } = await buildCases();
    const last = chunks[1].at(-1);
    expect(last).toMatchObject({
      i: 17,
      shopify_customer_id: "7000000000218",
      shopify_tags: ["neck", "vip"],
      shopify_note: "Synthetic Shopify note",
      address: { country: "MY", postal_code: "50450", city: "Kuala Lumpur" },
    });
  });
});
