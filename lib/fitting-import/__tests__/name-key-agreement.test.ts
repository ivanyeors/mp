import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { nameKey } from "@/lib/fitting-import/google-form-csv";

/**
 * One person's fittings go to one Customer (ADR 0039 c): a row under another
 * email, or with none on a shared mobile, is that person's when the mobile
 * and the name agree. The preview compares names with `nameKey`;
 * `import_fitting_rows` compares them with `public.fitting_name_key`
 * (20261101100000_fitting_import_one_person.sql). Both must read every name
 * the same, or the preview would forecast a match the import does not make.
 *
 * Each name is decided by the TypeScript into name-cases.json;
 * supabase/tests/fitting-import/assert-name.sql requires the SQL to give the
 * same. Made-up names.
 *
 * Regenerate with
 *   UPDATE_SQL_CASES=1 pnpm vitest run lib/fitting-import/__tests__/name-key-agreement.test.ts
 * and run ./scripts/check-fitting-import-sql.sh.
 */

const CASES_PATH = join(process.cwd(), "supabase/tests/fitting-import/name-cases.json");

const NAMES: (string | null)[] = [
  "Mei Tan",
  "  mei   TAN ",
  "MEI\tTAN",
  "Mei\nTan",
  "Mei Tan",
  "Mei　Tan",
  "﻿Mei Tan",
  "Mei Tan ",
  "Tan Mei Ling",
  "Nur Aisyah binte Rahman",
  "Siti",
  "O'Brien",
  "Zoë",
  "陈美玲",
  "",
  "   ",
  null,
];

function buildCases() {
  return {
    about:
      "Generated by lib/fitting-import/__tests__/name-key-agreement.test.ts (UPDATE_SQL_CASES=1). `key` is " +
      "nameKey; supabase/tests/fitting-import/assert-name.sql requires public.fitting_name_key to give the same.",
    expected: NAMES.map((name) => ({ name, key: nameKey(name) })),
  };
}

describe("nameKey and public.fitting_name_key read every name the same", () => {
  it("name-cases.json holds the TypeScript's answer for every name", () => {
    const cases = buildCases();
    if (process.env.UPDATE_SQL_CASES) writeFileSync(CASES_PATH, `${JSON.stringify(cases, null, 2)}\n`);
    expect(JSON.parse(readFileSync(CASES_PATH, "utf8"))).toEqual(cases);
  });

  it("ignores case, spacing and the ends, and nothing else", () => {
    expect(nameKey("  mei   TAN ")).toBe("mei tan");
    expect(nameKey("Mei Tan")).toBe("mei tan");
    expect(nameKey("Tan Mei Ling")).not.toBe(nameKey("Mei Tan"));
    expect(nameKey("   ")).toBeNull();
    expect(nameKey(null)).toBeNull();
  });
});
