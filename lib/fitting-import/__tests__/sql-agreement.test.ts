import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { parseFittingFormCsv } from "@/lib/fitting-import/google-form-csv";
import { applyPayload, importRows } from "@/lib/fitting-import/apply";
import { normaliseRows, NO_EXISTING, planRows, settleWholeFile } from "@/lib/fitting-import/plan";
import { formCsv } from "./fixtures";

/**
 * The payload the server action hands `import_fitting_rows` must be the one
 * the SQL function reads (column names, types, the skip reasons), and the SQL
 * must decide each row as the preview forecast it. This writes the payload
 * for a fixture file, with the forecast against an empty database, to
 * supabase/tests/fitting-import/cases.json; assert-agreement.sql imports it
 * and requires the same outcomes.
 *
 * Regenerate with
 *   UPDATE_SQL_CASES=1 pnpm vitest run lib/fitting-import/__tests__/sql-agreement.test.ts
 * and run ./scripts/check-fitting-import-sql.sh.
 */

const CASES_PATH = join(process.cwd(), "supabase/tests/fitting-import/cases.json");
const NOW = Date.parse("2026-10-31T08:00:00Z");

const FILE = formCsv([
  {},
  { "Email:": "", "Mobile No: ": "8123 0002", Timestamp: "10/2/2026 10:00:00" },
  { Timestamp: "10/20/2026 3:15:00 PM", "Upload a photo of your back": "sent on WhatsApp", "Did you have acid reflux?": "Yes" },
  {},
  { "Email:": "", "Mobile No: ": "" },
  { Timestamp: "not a date" },
  // Avery again, under another email: the same mobile and name.
  { "Email:": "second@example.com", "Additional Notes": "Prefers a lower neck.\nRe-check in 3 months.", "Who were you referred from?": "Dr Tan" },
  // Someone else on Avery's mobile, then a visit of Avery's with only the mobile: two hold it, one is Avery Lim.
  { "Name:": "Kim Lim", "Email:": "kim.lim@example.com", Timestamp: "10/21/2026 10:00:00" },
  { "Email:": "", Timestamp: "10/22/2026 10:00:00", "A) Shoulder length Measurements (Inches)": "18.5" },
]);

function buildCases() {
  const { rows } = parseFittingFormCsv(FILE);
  const normalised = normaliseRows(rows.map((raw, i) => ({ i, raw })), "mdy", NOW);
  const forecast = settleWholeFile(normalised, planRows(normalised, NO_EXISTING));
  return {
    about:
      "Generated by lib/fitting-import/__tests__/sql-agreement.test.ts (UPDATE_SQL_CASES=1). `rows` is what the server " +
      "action sends import_fitting_rows; `forecast` the preview's outcomes against an empty database. " +
      "supabase/tests/fitting-import/assert-agreement.sql requires the SQL to decide the same.",
    rows: importRows(applyPayload(rows, "mdy"), "mdy", NOW),
    forecast,
  };
}

describe("the server action's payload and import_fitting_rows agree", () => {
  it("cases.json holds the payload and the forecast", () => {
    const cases = JSON.parse(JSON.stringify(buildCases()));
    if (process.env.UPDATE_SQL_CASES) writeFileSync(CASES_PATH, `${JSON.stringify(cases, null, 2)}\n`);
    expect(JSON.parse(readFileSync(CASES_PATH, "utf8"))).toEqual(cases);
  });

  it("covers every outcome a fresh database can give", () => {
    const outcomes = new Set(buildCases().forecast.map((p) => p.reason ?? p.outcome));
    for (const o of ["created", "matched_email", "matched_phone", "duplicate_in_file", "no_contact", "no_timestamp", "no_customer_for_mobile"]) {
      expect(outcomes).toContain(o);
    }
  });
});
