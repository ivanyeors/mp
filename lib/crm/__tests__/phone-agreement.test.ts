type Case = { phone: string | null; valid: boolean; status: ReturnType<typeof mobileStatus> };

function buildCases() {
  const expected: Case[] = PHONES.map((phone) => ({ phone, valid: isValidPhone(phone), status: mobileStatus(phone) }));
  return {
    about:
      "Generated by lib/crm/__tests__/phone-agreement.test.ts (UPDATE_SQL_CASES=1). `valid` is isValidPhone, " +
      "`status` the Mobile filter bucket; supabase/tests/customer-crm/assert-11-contact-status.sql requires " +
      "public.is_valid_phone, public.is_blank_phone and the overview to give the same.",
    expected,
  };
}

describe("isValidPhone and public.is_valid_phone run the same fixture", () => {
  it("phone-cases.json holds the TypeScript's answer for every phone", () => {
    const cases = buildCases();
    if (process.env.UPDATE_SQL_CASES) writeFileSync(CASES_PATH, `${JSON.stringify(cases, null, 2)}\n`);
    expect(JSON.parse(readFileSync(CASES_PATH, "utf8"))).toEqual(cases);
  });

  it("covers every Mobile bucket, and invalid is exactly a number on file that fails isValidPhone", () => {
    const { expected } = buildCases();
    const by = (s: Case["status"]) => expected.filter((c) => c.status === s);
    expect(by("missing").length).toBeGreaterThan(0);
    expect(by("valid").length).toBeGreaterThan(0);
    expect(by("invalid").length).toBeGreaterThan(0);
    expect(by("invalid").every((c) => c.phone?.trim() && !c.valid)).toBe(true);
    expect(expected.filter((c) => c.phone?.trim() && !c.valid)).toEqual(by("invalid"));
    expect(by("valid").every((c) => c.valid)).toBe(true);
  });
});
