import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { isValidPhone } from "@/lib/appointments/phone";
import { mobileStatus } from "@/lib/crm/contact-status";

/**
 * The list's Mobile filter and the Customer page's Mobile row must agree
 * (CRM slice 11). The page asks `isValidPhone` (lib/appointments/phone.ts); the
 * list asks `public.is_valid_phone` and `public.is_blank_phone` through the
 * overview's `phone_valid` and `has_phone` (20261020123000). Both run the same
 * fixture:
 *
 *  - here, every phone in PHONES is decided by the TypeScript, and the answers
 *    are `expected` in phone-cases.json;
 *  - supabase/tests/customer-crm/assert-11-contact-status.sql seeds a Customer
 *    per phone and requires *Mobile: invalid* to list exactly those whose
 *    phone fails `isValidPhone`, and the other two buckets likewise.
 *
 * After changing the fixture or the phone rules, regenerate with
 *   UPDATE_SQL_CASES=1 pnpm vitest run lib/crm/__tests__/phone-agreement.test.ts
 * and run the SQL assert.
 */

const CASES_PATH = join(process.cwd(), "supabase/tests/customer-crm/phone-cases.json");

/** Every branch of normalizePhone, and the inputs that sit on its edges. */
const PHONES: (string | null)[] = [
  null,
  "",
  " ",
  "\t \n",
  " ",
  // 8-digit local: mobile 8/9, landline 6, anything else invalid.
  "87805311",
  "91234567",
  "61234567",
  "12345678",
  "71234567",
  "8780 5311",
  "8780-5311",
  " 87805311 ",
  // +65, 65 and 065 prefixes, each with a good and a bad national part.
  "+6587805311",
  "+65 8780 5311",
  "+65 1234 5678",
  "6587805311",
  "6512345678",
  "06587805311",
  "06512345678",
  // A plus only counts as the first character after whitespace.
  "  +6587805311",
  " +6587805311",
  "　+447700900123",
  "​+6587805311",
  "65+87805311",
  // Overseas E.164: 8 to 15 digits after the plus.
  "+447700900123",
  "+65123456789",
  "+1234567",
  "+12345678",
  "+123456789012345",
  "+1234567890123456",
  "+",
  // Wrong lengths and noise.
  "8780531",
  "878053111",
  "658780531",
  "0658780531",
  "call me",
  "tel: 9123 4567",
  "８７８０５３１１",
];

type Case = { phone: string | null; valid: boolean; status: ReturnType<typeof mobileStatus> };

function buildCases() {
  const expected: Case[] = PHONES.map((phone) => ({ phone, valid: isValidPhone(phone), status: mobileStatus(phone) }));
  return {
    about:
      "Generated by lib/crm/__tests__/phone-agreement.test.ts (UPDATE_SQL_CASES=1). `valid` is isValidPhone, " +
      "`status` the Mobile filter bucket; supabase/tests/customer-crm/assert-11-contact-status.sql requires " +
      "public.is_valid_phone, public.is_blank_phone and the overview to give the same.",
    expected,
  };
}

describe("isValidPhone and public.is_valid_phone run the same fixture", () => {
  it("phone-cases.json holds the TypeScript's answer for every phone", () => {
    const cases = buildCases();
    if (process.env.UPDATE_SQL_CASES) writeFileSync(CASES_PATH, `${JSON.stringify(cases, null, 2)}\n`);
    expect(JSON.parse(readFileSync(CASES_PATH, "utf8"))).toEqual(cases);
  });

  it("covers every Mobile bucket, and invalid is exactly a number on file that fails isValidPhone", () => {
    const { expected } = buildCases();
    const by = (s: Case["status"]) => expected.filter((c) => c.status === s);
    expect(by("missing").length).toBeGreaterThan(0);
    expect(by("valid").length).toBeGreaterThan(0);
    expect(by("invalid").length).toBeGreaterThan(0);
    expect(by("invalid").every((c) => c.phone?.trim() && !c.valid)).toBe(true);
    expect(expected.filter((c) => c.phone?.trim() && !c.valid)).toEqual(by("invalid"));
    expect(by("valid").every((c) => c.valid)).toBe(true);
  });
});
