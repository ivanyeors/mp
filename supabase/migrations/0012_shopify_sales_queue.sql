-- Queue Shopify sales for manual template selection before committing inventory deductions

create table if not exists shopify_sales_queue (
  id bigint generated by default as identity primary key,
  shopify_order_id bigint not null,
  shopify_line_item_id bigint,
  shopify_variant_id bigint,
  kind text not null check (kind in ('pillow','bolster','part')),
  pillow_size text check (pillow_size in ('XS','S','M','L','XL')),
  bolster_variant text check (bolster_variant in ('short','medium','long')),
  item_id bigint references items(id) on delete cascade,
  quantity int not null check (quantity > 0),
  product_title text,
  variant_title text,
  sku text,
  status text not null default 'pending' check (status in ('pending','committed','cancelled')),
  chosen_template_id bigint references bom_templates(id) on delete set null,
  committed_at timestamptz,
  created_at timestamptz not null default now(),
  metadata jsonb default '{}'::jsonb,
  check (
    (kind = 'pillow' and pillow_size is not null and bolster_variant is null and item_id is null)
    or (kind = 'bolster' and pillow_size is null and bolster_variant is not null and item_id is null)
    or (kind = 'part' and pillow_size is null and bolster_variant is null and item_id is not null)
  )
);

-- Avoid duplicates on webhook retries
create unique index if not exists idx_shopify_sales_queue_unique
on shopify_sales_queue (shopify_order_id, coalesce(shopify_line_item_id, -1), coalesce(shopify_variant_id, -1), kind);

create index if not exists idx_shopify_sales_queue_status on shopify_sales_queue (status, created_at desc);


