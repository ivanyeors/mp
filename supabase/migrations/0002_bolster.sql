-- Bolster BOM lines (single-size product)
create table if not exists bolster_bom_lines (
  id bigint generated by default as identity primary key,
  item_id bigint not null references items(id) on delete restrict,
  quantity numeric not null check (quantity > 0),
  unique (item_id)
);

comment on table bolster_bom_lines is 'BOM lines for the single-size bolster configuration';

