-- BOM templates for pillows (per size) and bolsters (per variant)

create table if not exists bom_templates (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('pillow','bolster')),
  name text not null,
  -- For pillows this is XS/S/M/L/XL; for bolsters this is short/medium/long
  key text not null,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (kind, key, name)
);

create index if not exists idx_bom_templates_kind_key on bom_templates (kind, key);

drop trigger if exists trg_bom_templates_updated_at on bom_templates;
create trigger trg_bom_templates_updated_at
before update on bom_templates
for each row execute procedure set_updated_at();

create table if not exists bom_template_lines (
  template_id bigint not null references bom_templates(id) on delete cascade,
  item_id bigint not null references items(id) on delete restrict,
  quantity numeric not null check (quantity > 0),
  primary key (template_id, item_id)
);

create index if not exists idx_bom_template_lines_template on bom_template_lines (template_id);


