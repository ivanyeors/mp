-- Tables
create table if not exists items (
  id bigint generated by default as identity primary key,
  category text not null check (category in ('cover','case','protector','filling','packaging')),
  subtype text,
  name text not null,
  size text,
  uom text not null default 'unit',
  is_active boolean not null default true
);

create unique index if not exists idx_items_category_size_subtype_name
on items (category, coalesce(size,'~'), coalesce(subtype,'~'), name);

create table if not exists pillow_products (
  id bigint generated by default as identity primary key,
  size text not null check (size in ('XS','S','M','L','XL')),
  is_active boolean not null default true,
  unique (size)
);

create table if not exists bom_lines (
  id bigint generated by default as identity primary key,
  product_id bigint not null references pillow_products(id) on delete cascade,
  item_id bigint not null references items(id) on delete restrict,
  quantity numeric not null check (quantity > 0),
  unique (product_id, item_id)
);

create table if not exists inventory_transactions (
  id bigint generated by default as identity primary key,
  item_id bigint not null references items(id) on delete restrict,
  quantity_signed numeric not null check (quantity_signed <> 0),
  reason text not null check (reason in ('sale','adjustment','receive','assemble','correction')),
  metadata jsonb default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists item_thresholds (
  item_id bigint primary key references items(id) on delete cascade,
  min_level numeric not null check (min_level >= 0)
);

-- Views
create or replace view inventory_balances as
select item_id, coalesce(sum(quantity_signed),0) as on_hand
from inventory_transactions
group by item_id;

create or replace view product_buildable as
select p.id as product_id,
       p.size,
       min( floor( coalesce(bal.on_hand,0) / bl.quantity ) )::bigint as buildable
from pillow_products p
join bom_lines bl on bl.product_id = p.id
left join inventory_balances bal on bal.item_id = bl.item_id
group by p.id, p.size;

