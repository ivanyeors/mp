-- M: 3D-L x1, 6D-S x1
insert into bom_lines (product_id, item_id, quantity)
select p.id, f.id, q.qty
from pillow_products p
join (
  select '3D-L' as subtype, 1 as qty union all
  select '6D-S', 1
) q on true
join items f on f.category='filling' and f.subtype = q.subtype
where p.size='M'
on conflict do nothing;

