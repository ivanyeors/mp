-- Default packaging mapping via BOM lines (1 each)
with products as (
  select id, size from pillow_products
), items_pack as (
  select id, name, size from items where category='packaging'
)
insert into bom_lines (product_id, item_id, quantity)
select p.id, i.id, 1
from products p
join items_pack i
  on ( (p.size in ('XS','S','M') and i.size='S') or (p.size in ('L','XL') and i.size='L') )
 and i.name in ('vacuum_bag','laundry_net')
on conflict do nothing;

-- Default core components (1 each): cover, case, protector sized to product
with products as (
  select id, size from pillow_products
), items_sized as (
  select id, category, size from items where category in ('cover','case','protector')
)
insert into bom_lines (product_id, item_id, quantity)
select p.id, i.id, 1
from products p
join items_sized i on i.size = p.size
on conflict do nothing;

