"use client";

import { useCallback, useEffect, useState } from "react";
import Image from "next/image";
import Link from "next/link";
import { usePathname } from "next/navigation";
import { Loader2, Package, PackagePlus, Pencil } from "lucide-react";
import { toast } from "sonner";
import { savedToasts } from "@/lib/shop/stripe-warnings";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Switch } from "@/components/ui/switch";
import { formatCurrency } from "@/lib/i18n/currencies";
import { DEFAULT_LOCALE } from "@/lib/i18n/locales";
import { getLocaleFromPathname, withLocale } from "@/lib/i18n/routing";
import type { ShopProductListing } from "@/lib/ecommerce/inventory-families";

function priceLabel(row: ShopProductListing): string | null {
  if (row.priceMinCents == null) return null;
  const min = formatCurrency(row.priceMinCents / 100);
  if (row.priceMaxCents == null || row.priceMaxCents === row.priceMinCents) return min;
  return `${min} to ${formatCurrency(row.priceMaxCents / 100)}`;
}

function detailLabel(row: ShopProductListing): string {
  const n = row.variantCount;
  const count = row.isAutoGenerated
    ? n === 1
      ? "One size"
      : `${n} sizes`
    : `${n} variant${n === 1 ? "" : "s"}`;
  return [count, priceLabel(row)].filter(Boolean).join(", ");
}

async function fetchListings(): Promise<ShopProductListing[]> {
  const res = await fetch("/api/shop/products/listings");
  const json = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(json.error ?? "Couldn't load products.");
  return json.rows ?? [];
}

export function ShopListingToggles({ onAddFromInventory }: { onAddFromInventory?: () => void }) {
  const pathname = usePathname() ?? "/";
  const locale = getLocaleFromPathname(pathname) ?? DEFAULT_LOCALE;
  const to = useCallback((p: string) => withLocale(p, locale), [locale]);

  const [loaded, setLoaded] = useState<ShopProductListing[] | null>(null);
  const [pendingId, setPendingId] = useState<string | null>(null);
  const [search, setSearch] = useState("");
  const rows = loaded ?? [];
  const loading = loaded === null;
  const setRows = (update: (prev: ShopProductListing[]) => ShopProductListing[]) =>
    setLoaded((prev) => update(prev ?? []));

  const load = useCallback(
    () =>
      fetchListings()
        .then(setLoaded)
        .catch((err: unknown) => {
          toast.error(err instanceof Error ? err.message : "Couldn't load products.");
          setLoaded([]);
        }),
    [],
  );

  useEffect(() => {
    void load();
  }, [load]);

  const toggle = async (row: ShopProductListing, listed: boolean) => {
    setPendingId(row.id);
    setRows((prev) => prev.map((r) => (r.id === row.id ? { ...r, listed } : r)));
    try {
      const res = await fetch("/api/shop/products/listings", {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ product_id: row.id, listed }),
      });
      const json = await res.json().catch(() => ({}));
      if (!res.ok) throw new Error(json.error ?? "Couldn't update.");
      const done = listed ? `${row.title} is now in the shop` : `${row.title} removed from the shop`;
      for (const t of savedToasts(done, { stripeWarnings: json.stripe_warnings })) toast[t.type](t.title, t.options);
      if (listed) void load();
    } catch (err) {
      setRows((prev) => prev.map((r) => (r.id === row.id ? { ...r, listed: !listed } : r)));
      toast.error(err instanceof Error ? err.message : "Couldn't update.");
    } finally {
      setPendingId(null);
    }
  };

  const q = search.trim().toLowerCase();
  const visible = q
    ? rows.filter(
        (r) => r.title.toLowerCase().includes(q) || (r.categoryName ?? "").toLowerCase().includes(q),
      )
    : rows;

  const byCategory = new Map<string, ShopProductListing[]>();
  for (const row of visible) {
    const key = row.categoryName ?? "No category";
    const list = byCategory.get(key) ?? [];
    list.push(row);
    byCategory.set(key, list);
  }

  const listedCount = rows.filter((r) => r.listed).length;

  return (
    <div className="space-y-3">
      <div className="rounded-xl border">
        <div className="flex flex-col gap-3 border-b px-4 py-3 sm:flex-row sm:items-center sm:justify-between">
          <div className="min-w-0">
            <h2 className="text-sm font-medium">What&apos;s in the shop</h2>
            <p className="text-xs text-muted-foreground">
              Switch on a product from the Products tab to sell it at its MSRP from Costings. New
              items come from Inventory through Add from Inventory.
            </p>
            <p className="mt-1 text-xs font-medium">
              {loading ? "Loading products…" : `${listedCount} of ${rows.length} in the shop`}
            </p>
          </div>
          <Input
            placeholder="Search products…"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="sm:w-64"
          />
        </div>

        {loading ? (
          <div className="flex items-center justify-center py-12">
            <Loader2 className="h-5 w-5 animate-spin text-muted-foreground" />
          </div>
        ) : visible.length === 0 ? (
          <div className="space-y-3 px-4 py-10 text-center text-sm text-muted-foreground">
            <p>
              {rows.length === 0
                ? "No products yet. Push items from Inventory to Products first."
                : "Nothing matches your search."}
            </p>
            {rows.length === 0 && onAddFromInventory ? (
              <Button size="sm" variant="outline" onClick={onAddFromInventory}>
                <PackagePlus className="mr-2 h-4 w-4" />
                Add from Inventory
              </Button>
            ) : null}
          </div>
        ) : (
          [...byCategory.entries()].map(([category, group]) => (
            <div key={category}>
              <div className="flex items-center justify-between gap-3 bg-muted/50 px-4 py-1.5 text-xs font-medium text-muted-foreground">
                <span>{category}</span>
                <span className="font-normal">
                  {group.filter((r) => r.listed).length} of {group.length} in the shop
                </span>
              </div>
              <ul className="divide-y">
                {group.map((row) => (
                  <li key={row.id} className="flex items-center justify-between gap-3 px-4 py-2.5">
                    <div className="flex min-w-0 items-center gap-3">
                      {row.thumbnailUrl ? (
                        <div className="relative h-9 w-9 shrink-0 overflow-hidden rounded-md border bg-muted">
                          <Image src={row.thumbnailUrl} alt="" fill className="object-cover" sizes="36px" />
                        </div>
                      ) : (
                        <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-md border bg-muted">
                          <Package className="h-4 w-4 text-muted-foreground/50" aria-hidden />
                        </div>
                      )}
                      <div className="min-w-0">
                        <div className="flex items-center gap-1.5">
                          <span className="truncate text-sm font-medium">{row.title}</span>
                          <Link
                            href={to(`/settings/products/${row.id}`)}
                            className="-m-2 rounded-md p-2 text-muted-foreground hover:text-foreground active:bg-press"
                            aria-label={`Edit ${row.title}: photos and description`}
                          >
                            <Pencil className="h-3.5 w-3.5" />
                          </Link>
                        </div>
                        <div className="text-xs text-muted-foreground">{detailLabel(row)}</div>
                        {row.blocker && !row.listed ? (
                          <div className="text-xs text-amber-700 dark:text-amber-300">{row.blocker}</div>
                        ) : null}
                      </div>
                    </div>
                    <Switch
                      checked={row.listed}
                      disabled={pendingId === row.id || (!!row.blocker && !row.listed)}
                      onCheckedChange={(checked) => void toggle(row, checked)}
                      aria-label={`Sell ${row.title} in the shop`}
                    />
                  </li>
                ))}
              </ul>
            </div>
          ))
        )}
      </div>
      <p className="px-1 text-xs text-muted-foreground">
        Pillows and bolsters are sold through the configurator, so they aren&apos;t listed here.
      </p>
    </div>
  );
}
