const BOLSTER_VARIANTS = ["short", "medium", "long"] as const;
type BolsterVariant = (typeof BOLSTER_VARIANTS)[number];

type ProductComponent = { itemId: number; quantity: number };

type ProductSummary = {
  key: string;
  kind: "pillow" | "bolster";
  productId: number | null;
  variant: BolsterVariant | null;
  costCents: number | null;
  cost: string | null;
  msrpCents: number | null;
  msrp: string | null;
};

const pillowKey = (productId: number) => `product:pillow:${productId}`;
const bolsterKey = (variant: BolsterVariant) => `product:bolster:${variant}`;

const toCents = (value: unknown): number | null => {
  if (value === null || value === undefined) return null;
  const numeric = typeof value === "number" ? value : Number.parseFloat(String(value));
  if (Number.isNaN(numeric)) return null;
  return Math.round(numeric * 100);
};

const Cents = z.number().int().min(0);

const ProductPayloadSchema = z
  .object({
    key: z.string().min(1),
    kind: z.enum(["pillow", "bolster"]),
    productId: z.number().int().positive().optional(),
    variant: z.enum(["short", "medium", "long", "linen", "fibrecool"]).optional(),
    msrpCents: Cents.nullable(),
    compareAtCents: Cents.nullable().optional(),
    base: z.object({ msrpCents: Cents.nullable(), compareAtCents: Cents.nullable() }),
  })
  .superRefine((value, ctx) => {
    if (value.kind === "pillow") {
      if (value.productId === undefined) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ["productId"],
          message: "productId is required for pillow products",
        });
      }
      if (value.variant !== undefined && value.variant !== "linen" && value.variant !== "fibrecool") {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ["variant"],
          message: "a pillow variant must be a case fabric family (linen | fibrecool)",
        });
      }
    } else if (value.kind === "bolster") {
      if (value.variant !== "short" && value.variant !== "medium" && value.variant !== "long") {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ["variant"],
          message: "a bolster variant must be a length (short | medium | long)",
        });
      }
      if (value.productId !== undefined) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ["productId"],
          message: "productId must be omitted for bolster products",
        });
      }
    }
  });

const PayloadSchema = z.object({
  rows: z.array(
    z.object({
      itemId: z.number().int().positive(),
      costPriceCents: Cents.nullable(),
      msrpCents: Cents.nullable(),
      compareAtCents: Cents.nullable().optional(),
      base: z.object({ costPriceCents: Cents.nullable(), msrpCents: Cents.nullable(), compareAtCents: Cents.nullable() }),
    }),
  ),
  products: z.array(ProductPayloadSchema).optional(),
  services: z
    .array(
      z.object({
        key: z.enum(SERVICE_KEYS),
        msrpCents: Cents,
        costCents: Cents.nullable(),
        base: z.object({ msrpCents: Cents, costCents: Cents.nullable() }),
      }),
    )
    .superRefine((rows, ctx) => {
      rows.forEach((r, i) => {
        if (r.key === "readjustment" && !isValidReadjustmentFeeCents(r.msrpCents)) {
          ctx.addIssue({
            code: "custom",
            path: [i, "msrpCents"],
            message: "must be $0, or $0.50 or more. Card payments can't be smaller.",
          });
        }
      });
    })
    .optional(),
  readjustmentPolicy: z
    .object({
      freeVisits: z.number().int().min(0).max(READJUSTMENT_POLICY_LIMITS.freeVisits),
      freeWindowDays: z.number().int().min(0).max(READJUSTMENT_POLICY_LIMITS.freeWindowDays),
      base: z.object({ freeVisits: z.number().int().min(0), freeWindowDays: z.number().int().min(0) }),
    })
    .optional(),
});

type ProductPayload = z.infer<typeof ProductPayloadSchema>;
type Payload = z.infer<typeof PayloadSchema>;
type PriceConflict = { key: string; name: string };

const READJUSTMENT_POLICY_NAME = "Complimentary re-adjustment";

function conflictMessage(names: readonly string[]): string {
  return names.length === 1
    ? `Someone changed this price since you opened it — reload to see it: ${names[0]}.`
    : `Someone changed these prices since you opened them — reload to see them: ${names.join(", ")}.`;
}

const productRef = (row: ProductPayload) =>
  row.kind === "pillow"
    ? {
        kind: "pillow" as const,
        key: row.key,
        productId: row.productId!,
        premiumVariant: row.variant === "linen" || row.variant === "fibrecool" ? row.variant : null,
      }
    : { kind: "bolster" as const, variant: row.variant as "short" | "medium" | "long" };

async function findPriceConflicts(
  admin: ReturnType<typeof supabaseAdmin>,
  payload: Payload,
): Promise<PriceConflict[]> {
  type StoredItemPrice = {
    item_id: number;
    cost_price: string | number | null;
    msrp: string | number | null;
    compare_at_price: string | number | null;
  };
  const products = payload.products ?? [];
  const services = payload.services ?? [];
  const policy = payload.readjustmentPolicy;

  const [itemRead, productRead, storedServices, storedPolicy] = await Promise.all([
    payload.rows.length > 0
      ? admin
          .from("item_prices")
          .select("item_id,cost_price,msrp,compare_at_price")
          .in("item_id", payload.rows.map((row) => row.itemId))
      : { data: [], error: null },
    products.length > 0
      ? admin.from("product_prices").select("key,kind,product_id,variant,msrp,compare_at_price")
      : { data: [], error: null },
    services.length > 0 ? loadServicePrices(admin) : null,
    policy ? loadReadjustmentPolicy(admin) : null,
  ]);
  if (itemRead.error) throw new Error(itemRead.error.message);
  if (productRead.error) throw new Error(productRead.error.message);

  const storedItems = new Map(
    ((itemRead.data ?? []) as StoredItemPrice[]).map((row) => [Number(row.item_id), row]),
  );
  const staleItemIds = payload.rows
    .filter((row) => {
      const stored = storedItems.get(row.itemId);
      return (
        toCents(stored?.cost_price ?? null) !== row.base.costPriceCents ||
        toCents(stored?.msrp ?? null) !== row.base.msrpCents ||
        toCents(stored?.compare_at_price ?? null) !== row.base.compareAtCents
      );
    })
    .map((row) => row.itemId);

  const storedProducts = (productRead.data ?? []) as StoredProductPrice[];
  const staleProducts = products.filter((row) => {
    const stored = storedProductPrice(storedProducts, productRef(row));
    return (
      toCents(stored?.msrp ?? null) !== row.base.msrpCents ||
      toCents(stored?.compare_at_price ?? null) !== row.base.compareAtCents
    );
  });

  const staleServices = storedServices
    ? services.filter(
        (row) =>
          toCents(storedServices[row.key].msrp) !== row.base.msrpCents ||
          toCents(storedServices[row.key].costPrice) !== row.base.costCents,
      )
    : [];

  const stalePolicy =
    policy && storedPolicy
      ? storedPolicy.freeVisits !== policy.base.freeVisits || storedPolicy.freeWindowDays !== policy.base.freeWindowDays
      : false;

  if (staleItemIds.length === 0 && staleProducts.length === 0 && staleServices.length === 0 && !stalePolicy) {
    return [];
  }

  const pillowIds = staleProducts.flatMap((row) => (row.kind === "pillow" && row.productId ? [row.productId] : []));
  const [itemNames, pillowNames] = await Promise.all([
    staleItemIds.length > 0
      ? admin.from("items").select("id,category,name,size,subtype").in("id", staleItemIds)
      : { data: [], error: null },
    pillowIds.length > 0 ? admin.from("pillow_products").select("id,size").in("id", pillowIds) : { data: [], error: null },
  ]);
  type NamedItem = { id: number; category: string; name: string | null; size: string | null; subtype: string | null };
  const itemById = new Map(((itemNames.data ?? []) as NamedItem[]).map((item) => [Number(item.id), item]));
  const sizeByPillow = new Map(
    ((pillowNames.data ?? []) as Array<{ id: number; size: string }>).map((pillow) => [Number(pillow.id), pillow.size]),
  );

  return [
    ...staleItemIds.map((itemId) => {
      const item = itemById.get(itemId);
      return { key: `item:${itemId}`, name: item ? getInventoryItemDisplayLabel(item) : `Item ${itemId}` };
    }),
    ...staleProducts.map((row) => {
      const ref = productRef(row);
      const name =
        ref.kind === "bolster"
          ? productPriceLabel(ref)
          : productPriceLabel({
              kind: "pillow",
              size: sizeByPillow.get(ref.productId) ?? `#${ref.productId}`,
              premiumVariant: ref.premiumVariant,
            });
      return { key: row.key, name };
    }),
    ...staleServices.map((row) => ({ key: row.key, name: SERVICE_LABELS[row.key] })),
    ...(stalePolicy ? [{ key: "readjustmentPolicy", name: READJUSTMENT_POLICY_NAME }] : []),
  ];
}

const toDecimalString = (value: number | null) => (value === null ? null : (value / 100).toFixed(2));

async function fetchProductSummaries(adminClient: ReturnType<typeof supabaseAdmin>): Promise<ProductSummary[]> {
  type RawItemRow = { id: number; pricing?: { cost_price: string | number | null } | Array<{ cost_price: string | number | null }> | null };
  type RawPillowRow = { id: number; size: string; kind: string | null };
  type RawBomLine = { product_id: number; item_id: number; quantity: number | string };
  type RawBolsterLine = { variant: string; item_id: number; quantity: number | string };
  type RawProductPrice = {
    key: string;
    kind: "pillow" | "bolster";
    product_id: number | null;
    variant: string | null;
    msrp: string | number | null;
  };

  const [
    { data: itemsData, error: itemsError },
    { data: pillowData, error: pillowError },
    { data: bomData, error: bomError },
    { data: bolsterData, error: bolsterError },
    { data: productPricesData, error: productPricesError },
  ] = await Promise.all([
    adminClient
      .from("items")
      .select("id,pricing:item_prices!left(cost_price)")
      .eq("is_active", true),
    adminClient.from("pillow_products").select("id,size,kind").eq("is_active", true),
    adminClient.from("bom_lines").select("product_id,item_id,quantity"),
    adminClient.from("bolster_bom_lines").select("variant,item_id,quantity"),
    adminClient.from("product_prices").select("key,kind,product_id,variant,msrp"),
  ]);

  if (itemsError) throw new Error(itemsError.message);
  if (pillowError) throw new Error(pillowError.message);
  if (bomError) throw new Error(bomError.message);
  if (bolsterError) throw new Error(bolsterError.message);
  if (productPricesError) throw new Error(productPricesError.message);

  const itemCostById = new Map<number, number | null>();
  (itemsData ?? []).forEach((row: RawItemRow) => {
    const pricing = Array.isArray(row.pricing) ? row.pricing[0] : row.pricing;
    const costCents = toCents(pricing?.cost_price ?? null);
    itemCostById.set(row.id, costCents);
  });

  const bomByProduct = new Map<number, ProductComponent[]>();
  (bomData ?? []).forEach((line: RawBomLine) => {
    const productId = Number(line.product_id);
    const itemId = Number(line.item_id);
    const quantity = Number(line.quantity);
    if (!Number.isFinite(productId) || !Number.isFinite(itemId) || !Number.isFinite(quantity)) {
      return;
    }
    const list = bomByProduct.get(productId) ?? [];
    list.push({ itemId, quantity });
    bomByProduct.set(productId, list);
  });

  const bolsterByVariant: Record<BolsterVariant, ProductComponent[]> = {
    short: [],
    medium: [],
    long: [],
  };
  (bolsterData ?? []).forEach((line: RawBolsterLine) => {
    const variant = line.variant;
    if (variant !== "short" && variant !== "medium" && variant !== "long") return;
    const itemId = Number(line.item_id);
    const quantity = Number(line.quantity);
    if (!Number.isFinite(itemId) || !Number.isFinite(quantity)) return;
    bolsterByVariant[variant].push({ itemId, quantity });
  });

  const priceByProductId = new Map<number, RawProductPrice>();
  const priceByVariant = new Map<BolsterVariant, RawProductPrice>();
  (productPricesData ?? []).forEach((row: RawProductPrice) => {
    if (row.kind === "pillow" && row.product_id !== null) {
      priceByProductId.set(row.product_id, row);
    } else if (row.kind === "bolster" && row.variant && (row.variant === "short" || row.variant === "medium" || row.variant === "long")) {
      priceByVariant.set(row.variant as BolsterVariant, row);
    }
  });

  const costForComponents = (components: ProductComponent[]): number | null => {
    if (components.length === 0) return 0;
    let total = 0;
    for (const component of components) {
      const cost = itemCostById.get(component.itemId);
      if (cost === undefined || cost === null) {
        return null;
      }
      total += cost * component.quantity;
    }
    return Math.round(total);
  };

  const summaries: ProductSummary[] = [];

  (pillowData ?? []).forEach((product: RawPillowRow) => {
    const key = pillowKey(product.id);
    const components = bomByProduct.get(product.id) ?? [];
    const costCents = costForComponents(components);
    const price = priceByProductId.get(product.id);
    const msrpCents = toCents(price?.msrp ?? null);
    summaries.push({
      key,
      kind: "pillow",
      productId: product.id,
      variant: null,
      costCents,
      cost: toDecimalString(costCents),
      msrpCents,
      msrp: toDecimalString(msrpCents),
    });
  });

  BOLSTER_VARIANTS.forEach((variant) => {
    const key = bolsterKey(variant);
    const components = bolsterByVariant[variant];
    const costCents = costForComponents(components);
    const price = priceByVariant.get(variant);
    const msrpCents = toCents(price?.msrp ?? null);
    summaries.push({
      key,
      kind: "bolster",
      productId: null,
      variant,
      costCents,
      cost: toDecimalString(costCents),
      msrpCents,
      msrp: toDecimalString(msrpCents),
    });
  });

  return summaries;
}

type ServicePayload = NonNullable<z.infer<typeof PayloadSchema>["services"]>;
type PolicyPayload = z.infer<typeof PayloadSchema>["readjustmentPolicy"];

async function saveServices(
  admin: ReturnType<typeof supabaseAdmin>,
  services: ServicePayload,
  policy: PolicyPayload,
) {
  const [beforeServices, beforePolicy] = await Promise.all([
    loadServicePrices(admin).catch(() => null),
    loadReadjustmentPolicy(admin).catch(() => null),
  ]);
  const now = new Date().toISOString();

  if (services.length > 0) {
    const { error } = await admin.from("service_prices").upsert(
      services.map((s) => ({
        key: s.key,
        msrp: toDecimalString(s.msrpCents),
        cost_price: toDecimalString(s.costCents),
        currency: "SGD",
        updated_at: now,
      })),
      { onConflict: "key" },
    );
    if (error) throw new Error(error.message);
  }

  if (policy) {
    const { error } = await admin.from("site_settings").upsert(
      [
        { key: "readjustment_free_visits", value: String(policy.freeVisits), updated_at: now },
        { key: "readjustment_free_window_days", value: String(policy.freeWindowDays), updated_at: now },
      ],
      { onConflict: "key" },
    );
    if (error) throw new Error(error.message);
    invalidateTag("site-settings");
  }

  const [afterServices, afterPolicy] = await Promise.all([
    loadServicePrices(admin),
    loadReadjustmentPolicy(admin),
  ]);
  await recordAdminAction({
    actor: await getAdminContext(),
    action: "costings.service_fees_update",
    entityType: "service_prices",
    before: { services: beforeServices, readjustmentPolicy: beforePolicy },
    after: { services: afterServices, readjustmentPolicy: afterPolicy },
  });
}

export async function POST(req: Request) {
  const denied = await requireAdmin("costings");
  if (denied) return denied;

  let payload: z.infer<typeof PayloadSchema>;
  try {
    const json = await req.json();
    const parsed = PayloadSchema.safeParse(json);
    if (!parsed.success) {
      const issue = parsed.error.issues[0];
      const field = issue?.path.join(".") || "payload";
      return NextResponse.json({ error: `Invalid ${field}: ${issue?.message ?? "invalid"}` }, { status: 400 });
    }
    payload = parsed.data;
  } catch {
    return NextResponse.json({ error: "Invalid payload" }, { status: 400 });
  }

  const productRows = payload.products ?? [];
  const admin = supabaseAdmin();

  let conflicts: PriceConflict[];
  try {
    // ponytail: check-then-write, so a save landing between this read and the writes below is still
    // overwritten (a window of one round trip). Upgrade: one Postgres function that locks the rows
    // (select ... for update), compares each base and writes, all in one transaction.
    conflicts = await findPriceConflicts(admin, payload);
  } catch (err) {
    const message = err instanceof Error ? err.message : "Couldn't check the saved prices.";
    return NextResponse.json({ error: message }, { status: 500 });
  }
  if (conflicts.length > 0) {
    return NextResponse.json(
      { error: conflictMessage(conflicts.map((conflict) => conflict.name)), conflicts },
      { status: 409 },
    );
  }

  if (payload.services || payload.readjustmentPolicy) {
    try {
      await saveServices(admin, payload.services ?? [], payload.readjustmentPolicy);
    } catch (err) {
      const message = err instanceof Error ? err.message : "Couldn't save service fees.";
      return NextResponse.json({ error: message }, { status: 500 });
    }
  }

  if (payload.rows.length === 0 && productRows.length === 0) {
    if (payload.services || payload.readjustmentPolicy) {
      const [services, readjustmentPolicy] = await Promise.all([
        loadServicePrices(admin),
        loadReadjustmentPolicy(admin),
      ]);
      return NextResponse.json({ ok: true, products: [], services, readjustmentPolicy });
    }
    return NextResponse.json({ ok: true, products: [] });
  }

  const upsertRows = payload.rows
    .filter((row) => row.costPriceCents !== null || row.msrpCents !== null || row.compareAtCents !== null)
    .map((row) => ({
      item_id: row.itemId,
      cost_price: toDecimalString(row.costPriceCents),
      msrp: toDecimalString(row.msrpCents),
      compare_at_price: toDecimalString(row.compareAtCents ?? null),
    }));

  const deleteIds = payload.rows
    .filter((row) => row.costPriceCents === null && row.msrpCents === null && (row.compareAtCents ?? null) === null)
    .map((row) => row.itemId);

  try {
    if (upsertRows.length > 0) {
      const { error } = await admin.from("item_prices").upsert(upsertRows);
      if (error) throw new Error(error.message);
    }
    if (deleteIds.length > 0) {
      const { error } = await admin.from("item_prices").delete().in("item_id", deleteIds);
      if (error) throw new Error(error.message);
    }
    if (productRows.length > 0) {
      const productUpserts = productRows
        .filter((row): row is ProductPayload => row.msrpCents !== null || (row.compareAtCents ?? null) !== null)
        .map((row) => ({
          key: row.key,
          kind: row.kind,
          product_id: row.kind === "pillow" ? row.productId! : null,
          variant: row.variant ?? null,
          msrp: toDecimalString(row.msrpCents),
          compare_at_price: toDecimalString(row.compareAtCents ?? null),
          currency: "SGD",
        }));
      if (productUpserts.length > 0) {
        const { error } = await admin.from("product_prices").upsert(productUpserts, { onConflict: "key" });
        if (error) throw new Error(error.message);
      }
      const deleteKeys = productRows
        .filter((row) => row.msrpCents === null && (row.compareAtCents ?? null) === null)
        .map((row) => row.key);
      if (deleteKeys.length > 0) {
        const { error } = await admin.from("product_prices").delete().in("key", deleteKeys);
        if (error) throw new Error(error.message);
      }
    }
    const { results: priceSyncResults, stripeWarnings } = await syncAllAutoGeneratedProductPrices();
    const unresolvable = priceSyncResults.flatMap((r) => r.unresolvable);

    // ponytail: all gap/Others lines — healthy frozen stay frozen inside reResolve.
    after(() => {
      void reResolveShopifyLineCosts().catch((err) => {
        console.error("[shopify-mirror] re-resolve failed", err);
      });
    });

    const products = await fetchProductSummaries(admin);
    return NextResponse.json({
      ok: true,
      products,
      unresolvable_variants: unresolvable.length > 0 ? unresolvable : undefined,
      stripe_warnings: stripeWarnings.length > 0 ? stripeWarnings : undefined,
    });
  } catch (err) {
    const message = err instanceof Error ? err.message : "Couldn't save prices.";
    return NextResponse.json({ error: message }, { status: 500 });
  }
}


