import { NextResponse } from "next/server";
import { requireAdmin } from "@/lib/auth/admin";
import { syncAllAutoGeneratedProductPrices } from "@/lib/shop/price-sync";

export const runtime = "nodejs";

export async function POST() {
  const denied = await requireAdmin("products");
  if (denied) return denied;

  try {
    const { results, stripeWarnings } = await syncAllAutoGeneratedProductPrices();
    const synced = results.reduce((sum, r) => sum + r.synced, 0);
    const unresolvable = results.flatMap((r) => r.unresolvable);
    return NextResponse.json({
      ok: true,
      synced,
      unresolvable: unresolvable.length > 0 ? unresolvable : undefined,
      stripe_warnings: stripeWarnings.length > 0 ? stripeWarnings : undefined,
      message: `Resynced ${synced} variant${synced === 1 ? "" : "s"} from Costings`,
    });
  } catch (err) {
    const message = err instanceof Error ? err.message : "Failed to resync prices";
    return NextResponse.json({ ok: false, error: message }, { status: 500 });
  }
}
